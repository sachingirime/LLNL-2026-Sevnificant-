#!/usr/bin/env python
"""The result as one poster table (PNG): what was found, and how well it checks out.

Two blocks, deliberately: the per-class counts are what the detector reported, and the
validation underneath is the only part of it that an independent source can confirm.
Keeping them apart stops the 0.989 from reading as if it covered every class — it covers
`missing` alone, because `missing` is the only class the CAD can adjudicate.

Counts come from the run's own strut_classes.csv; the validation numbers are passed in
(they come from validate_against_stl) so nothing here re-derives a score.

    python scripts/poster/results_table.py
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import FancyBboxPatch  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from scripts.classify_strut_defects import CLASS_COLORS, ORDER  # noqa: E402

INK, MUTED, RULE = "#0b0b0b", "#52514e", "#d8d7d1"
SURFACE, BAND = "#ffffff", "#f4f3ef"
GOOD_FC, GOOD_EC = "#eef7ee", "#0ca30c"

# From validate_against_stl on 0.5.stl against outputs/fresh_pass_.../defects.
# `designed_out` is read from the CAD mesh and owes the detector nothing.
VALIDATION = dict(designed_out=91, measurable=90, tp=88, fp=1, fn=2,
                  precision=0.989, recall=0.978, f1=0.983)

# Per class, same run. `necked` and `nominal` are absent from the tool's output: the CAD
# ground truth is a set defined by ABSENCE, so only classes that also assert absence can
# be scored against it. A present-but-pinched strut is not a thing the STL can adjudicate.
PER_CLASS = {
    "missing": dict(measurable=89,    tp=88, fp=1,    fn=2,  p=0.989, r=0.978, f1=0.983),
    "broken":  dict(measurable=152,   tp=2,  fp=150,  fn=88, p=0.013, r=0.022, f1=0.017),
    "thin":    dict(measurable=1650,  tp=0,  fp=1650, fn=90, p=0.0,   r=0.0,   f1=0.0),
    "thick":   dict(measurable=525,   tp=0,  fp=525,  fn=90, p=0.0,   r=0.0,   f1=0.0),
    "necked":  dict(measurable=15),
    "nominal": dict(measurable=14512),
}
ORIENTATION = "perm (2,0,1) signs (-1,-1,-1); 88 of 89 matched, runner-up 12, chance 0.4"


def emit_tex(counts: dict, total: int, out_path: Path) -> Path:
    """A booktabs table joining the CT counts to the CAD score, class by class."""
    def num(v):
        return f"{v:,}".replace(",", "{,}")

    rows = []
    for name in ORDER:
        c = PER_CLASS.get(name, {})
        cells = [f"\\texttt{{{name}}}", num(counts.get(name, 0)), num(c.get("measurable", 0))]
        if "tp" in c:
            cells += [num(c["tp"]), num(c["fp"]), num(c["fn"]),
                      f"{c['p']:.3f}", f"{c['r']:.3f}", f"{c['f1']:.3f}"]
        else:
            cells += ["--"] * 6
        rows.append("  " + " & ".join(cells) + r" \\")
    body = "\n".join(rows[:-1]) + "\n  \\midrule\n" + rows[-1]

    v = VALIDATION
    tex = f"""% Per-strut result: X-ray CT (.tif) against the CAD ground truth (0.5.stl).
% Generated by scripts/poster/results_table.py --tex — do not hand-edit.
% Requires \\usepackage{{booktabs}} (and \\usepackage{{siunitx}} if you want aligned decimals).
%
% Provenance:
%   CT columns          strut_classes.csv of the run
%   CAD columns         validate_against_stl on data/missing_struts/stls/0.5.stl
%   frame resolution    {ORIENTATION}
\\begin{{table}}[t]
  \\centering
  \\small
  \\caption{{Per-strut classification from the X-ray CT, scored against the
    {v['designed_out']} struts deliberately removed from the CAD model. Precision and
    recall are meaningful for \\texttt{{missing}} alone: the ground truth is a set defined by
    absence, so classes that assert a present-but-deformed strut cannot be scored against
    it. \\emph{{All}} counts every strut in the design; \\emph{{measurable}} excludes
    boundary-cap and embedded struts.}}
  \\label{{tab:perstrut}}
  \\begin{{tabular}}{{l rr rrr rrr}}
    \\toprule
    & \\multicolumn{{2}}{{c}}{{X-ray CT (\\texttt{{.tif}})}}
    & \\multicolumn{{6}}{{c}}{{Scored against CAD (\\texttt{{0.5.stl}})}} \\\\
    \\cmidrule(lr){{2-3}} \\cmidrule(lr){{4-9}}
    Class & All & Measurable & TP & FP & FN & P & R & F1 \\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}

  \\vspace{{2pt}}
  \\footnotesize
  Design total {num(total)} struts. The CAD removed {v['designed_out']}
  ({100 * v['designed_out'] / total:.3f}\\%), of which {v['measurable']} are measurable;
  \\texttt{{missing}}\\,$\\cup$\\,\\texttt{{broken}} recovers all {v['measurable']}.
\\end{{table}}
"""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(tex)
    return out_path


def load_counts(run_dir: Path):
    with (run_dir / "strut_classes.csv").open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    key = "label" if rows and "label" in rows[0] else "class"
    counts = {}
    for row in rows:
        counts[row[key]] = counts.get(row[key], 0) + 1
    return counts, len(rows)


def build(run_dir: Path, out_path: Path, title: str):
    counts, total = load_counts(run_dir)

    W, H = 7.6, 5.4
    fig, ax = plt.subplots(figsize=(W, H), dpi=300)
    fig.patch.set_facecolor(SURFACE)
    ax.set_xlim(0, W); ax.set_ylim(0, H); ax.axis("off")

    L, R = 0.34, W - 0.34
    ax.text(L, H - 0.30, title, fontsize=13.5, fontweight="bold", color=INK, va="top")
    ax.text(L, H - 0.62, f"every strut of the design, {total:,} in total",
            fontsize=8.8, color=MUTED, va="top", style="italic")

    # ---- header ---------------------------------------------------------------
    y = H - 1.00
    x_class, x_count, x_pct = L + 0.30, R - 1.55, R
    for label, xx, ha in (("class", x_class, "left"),
                          ("struts", x_count, "right"),
                          ("share", x_pct, "right")):
        ax.text(xx, y, label, fontsize=8.6, color=MUTED, ha=ha, va="center",
                fontweight="bold")
    y -= 0.13
    ax.plot([L, R], [y, y], color=RULE, lw=1.0)

    # ---- one row per class ----------------------------------------------------
    ROW = 0.40
    y -= 0.10
    for name in ORDER:
        n = counts.get(name, 0)
        y -= ROW
        if name == "nominal":                      # context, so set it off
            ax.plot([L, R], [y + ROW - 0.10, y + ROW - 0.10], color=RULE, lw=1.0)
        ax.add_patch(FancyBboxPatch((L, y - 0.075), 0.16, 0.16,
                                    boxstyle="round,pad=0,rounding_size=0.04",
                                    fc=CLASS_COLORS[name], ec="none", zorder=3))
        weight = "normal" if name == "nominal" else "bold"
        colour = MUTED if name == "nominal" else INK
        ax.text(x_class, y, name, fontsize=11, color=colour, va="center", fontweight=weight)
        ax.text(x_count, y, f"{n:,}", fontsize=11, color=colour, va="center",
                ha="right", fontweight=weight)
        ax.text(x_pct, y, f"{100 * n / total:.2f} %", fontsize=10, color=MUTED,
                va="center", ha="right")

    # ---- validation -----------------------------------------------------------
    v = VALIDATION
    bh = 1.28
    by = y - 0.42 - bh
    ax.add_patch(FancyBboxPatch((L, by), R - L, bh,
                                boxstyle="round,pad=0.012,rounding_size=0.05",
                                fc=GOOD_FC, ec=GOOD_EC, lw=1.4, zorder=2))
    ax.text(L + 0.22, by + bh - 0.24, "Checked against the CAD  (0.5.stl)",
            fontsize=10.5, fontweight="bold", color=INK, va="center", zorder=3)
    ax.text(L + 0.22, by + bh - 0.50,
            f"{v['designed_out']} struts were designed out; the detector found "
            f"{v['tp']} of them",
            fontsize=9, color=MUTED, va="center", zorder=3)

    cells = [("precision", f"{v['precision']:.3f}"), ("recall", f"{v['recall']:.3f}"),
             ("F1", f"{v['f1']:.3f}"), ("false alarms", str(v["fp"]))]
    cw = (R - L - 0.44) / len(cells)
    for i, (lab, val) in enumerate(cells):
        cx = L + 0.22 + cw * (i + 0.5)
        ax.text(cx, by + 0.44, val, fontsize=15, fontweight="bold", color=INK,
                ha="center", va="center", zorder=3)
        ax.text(cx, by + 0.19, lab, fontsize=8.4, color=MUTED, ha="center",
                va="center", zorder=3)

    ax.text(L, by - 0.20,
            "scores apply to `missing` only — it is the one class the CAD can adjudicate.",
            fontsize=8.2, color=MUTED, va="top")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=300, facecolor=SURFACE, bbox_inches="tight", pad_inches=0.22)
    plt.close(fig)
    return out_path


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run", default="outputs/fresh_pass_20260730T223536/defects")
    p.add_argument("-o", "--out", default="outputs/poster/results_table.png")
    p.add_argument("--title", default="Per-strut defect classification")
    p.add_argument("--tex", action="store_true", help="also emit a booktabs .tex table")
    args = p.parse_args()

    run_dir = Path(args.run) if Path(args.run).is_absolute() else ROOT / args.run
    out = Path(args.out) if Path(args.out).is_absolute() else ROOT / args.out
    counts, total = load_counts(run_dir)
    out = build(run_dir, out, args.title)
    print(f"wrote {out}  ({out.stat().st_size / 1e6:.2f} MB)")
    if args.tex:
        tex = emit_tex(counts, total, out.with_suffix(".tex"))
        print(f"wrote {tex}")


if __name__ == "__main__":
    main()
